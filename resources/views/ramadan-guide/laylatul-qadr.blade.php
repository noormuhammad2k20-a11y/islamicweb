      <h2>What is Laylatul Qadr?</h2>
      <p>Laylatul Qadr (لیلة القدر), often translated as the Night of Decree, Night of Power, or Night
      of Value, is the holiest night in the Islamic calendar. It takes place during the last ten
      days of Ramadan. It is the night when the Quran was first revealed to Prophet Muhammad ﷺ
      through the Angel Jibril (Gabriel).</p>

      <div class="quran-quote">
        <div class="arabic-text">إِنَّا أَنزَلْنَاهُ فِي لَيْلَةِ الْقَدْرِ ۝ وَمَا أَدْرَاكَ مَا لَيْلَةُ الْقَدْرِ ۝ لَيْلَةُ الْقَدْرِ خَيْرٌ مِّنْ أَلْفِ شَهْرٍ</div>
        <div class="translation">"Indeed, We sent the Qur'an down during the Night of Decree. And what can make you know what is the Night of Decree? The Night of Decree is better than a thousand months."</div>
        <div class="reference">— Surah Al-Qadr (97:1-3)</div>
      </div>

      <h2>When is Laylatul Qadr?</h2>
      <p>The exact date of Laylatul Qadr is hidden by Allah (SWT) so that Muslims strive in worship
      throughout the last ten nights. However, the Prophet ﷺ advised us to seek it in the odd-numbered
      nights of the last ten days of Ramadan: <strong>21st, 23rd, 25th, 27th, or 29th</strong>.</p>
      
      <p>In South Asian communities, the 27th night is widely observed (Shab-e-Qadr), but scholars
      advise worshiping vigorously on all odd nights to be absolutely certain of catching it.</p>

      <h2>What to do on Laylatul Qadr?</h2>
      
      <div class="dhikr-block">
        <h3>1. Recite the Special Dua</h3>
        <p>Aisha (RA) asked the Prophet ﷺ: "O Messenger of Allah, if I know what night is the Night
        of Qadr, what should I say during it?" He said: "Say: O Allah, You are pardoning and You love
        to pardon, so pardon me."</p>
        <div class="dua-arabic">اللَّهُمَّ إِنَّكَ عَفُوٌّ تُحِبُّ الْعَفْوَ فَاعْفُ عَنِّي</div>
        <div class="transliteration">Allahumma innaka 'afuwwun tuhibbul 'afwa fa'fu 'anni.</div>
      </div>

      <h3>2. Pray Tahajjud & Nawafil</h3>
      <p>Engage in extra prayers (Nafl) during the night. The Prophet ﷺ said: <em>"Whoever stands
      in prayer during Laylatul Qadr with faith and hoping for its reward will have all of his
      previous sins forgiven."</em> (Bukhari)</p>

      <h3>3. Read the Quran</h3>
      <p>Since this is the night the Quran was revealed, reciting, understanding, and reflecting
      upon the Quran is highly recommended.</p>

      <h3>4. Make Sincere Dua (Supplication)</h3>
      <p>On this night, the destinies for the coming year are decreed. Make dua for your worldly
      needs, your hereafter, your family, and the Muslim Ummah.</p>
