            <h3 style="font-size: 1.1rem; color: var(--primary-dark); margin-bottom: 8px;">1. Can I pay my Zakat in advance?</h3>
            <p style="font-size: 0.92rem; color: var(--text-medium); line-height: 1.8;">
                Yes, paying Zakat in advance is generally permissible in Islam. If you anticipate your wealth and pay early to help someone in urgent need, it is accepted. When your actual Zakat due date arrives, you simply calculate your exact liabilities. If you paid less, you make up the difference. If you paid more, it counts as voluntary charity (Sadaqah) or can be carried forward to next year depending on your intention.
            </p>
        </div>

        <div style="margin-bottom: 25px;">
            <h3 style="font-size: 1.1rem; color: var(--primary-dark); margin-bottom: 8px;">2. Do I have to pay Zakat on my house and car?</h3>
            <p style="font-size: 0.92rem; color: var(--text-medium); line-height: 1.8;">
                No. Personal use items, including your primary residence, the car you drive, your clothes, and your household furniture, are completely exempt from Zakat. Zakat is only due on wealth that has the potential to grow, such as cash, gold, silver, investments, and business inventory.
            </p>
        </div>

        <div style="margin-bottom: 25px;">
            <h3 style="font-size: 1.1rem; color: var(--primary-dark); margin-bottom: 8px;">3. Can I give Zakat to my immediate family members?</h3>
            <p style="font-size: 0.92rem; color: var(--text-medium); line-height: 1.8;">
                You cannot give Zakat to family members whom you are already financially obligated to support. This includes your parents, grandparents, children, and grandchildren. A husband cannot give Zakat to his wife. However, you can give Zakat to your brothers, sisters, uncles, or aunts, provided they are genuinely poor and meet the eligibility criteria.
            </p>
        </div>

        <div style="margin-bottom: 25px;">
            <h3 style="font-size: 1.1rem; color: var(--primary-dark); margin-bottom: 8px;">4. What if I forgot to pay Zakat for previous years?</h3>
            <p style="font-size: 0.92rem; color: var(--text-medium); line-height: 1.8;">
                If you missed paying Zakat in previous years, it remains a debt owed to Allah. You must estimate your wealth for those missed years as accurately as possible and pay the accumulated Zakat immediately. Repentance (Tawbah) is also necessary for delaying this obligatory pillar.
            </p>
        </div>

        <div style="margin-bottom: 25px;">
            <h3 style="font-size: 1.1rem; color: var(--primary-dark); margin-bottom: 8px;">5. How do I calculate Zakat on a mortgaged house?</h3>
            <p style="font-size: 0.92rem; color: var(--text-medium); line-height: 1.8;">
                If you live in the house, its value is exempt from Zakat. However, you may deduct the upcoming 12 months of mortgage payments (the immediate debt) from your total Zakatable cash and assets. You cannot deduct the entire 30-year mortgage balance, as that would unfairly eliminate your Zakat obligations on other wealth.
            </p>
        </div>

        <div style="margin-bottom: 25px;">
            <h3 style="font-size: 1.1rem; color: var(--primary-dark); margin-bottom: 8px;">6. Is Zakat required on women's personal jewellery?</h3>
            <p style="font-size: 0.92rem; color: var(--text-medium); line-height: 1.8;">
                This depends on your Fiqh (school of thought). In the Hanafi school, Zakat is strictly due on all gold and silver, regardless of whether it is worn daily or stored. In the Shafi, Maliki, and Hanbali schools, reasonable amounts of jewellery worn for personal use are exempt. However, any jewellery bought for investment purposes is universally Zakatable.
            </p>
        </div>

        <div style="margin-bottom: 25px;">
            <h3 style="font-size: 1.1rem; color: var(--primary-dark); margin-bottom: 8px;">7. My wealth fluctuates during the year. How do I calculate?</h3>
            <p style="font-size: 0.92rem; color: var(--text-medium); line-height: 1.8;">
                You do not need to track your wealth daily. You only need to know your wealth on your Zakat anniversary date. As long as your total wealth was above the Nisab at the beginning of the lunar year, and remains above the Nisab on your anniversary date, you pay 2.5% on whatever amount you have on that exact date, regardless of fluctuations in between.
            </p>
        </div>

        <div style="margin-bottom: 25px;">
            <h3 style="font-size: 1.1rem; color: var(--primary-dark); margin-bottom: 8px;">8. Do I pay Zakat on my 401(k), IRA, or Retirement Funds?</h3>
            <p style="font-size: 0.92rem; color: var(--text-medium); line-height: 1.8;">
                Yes, Zakat is due on retirement funds, but the calculation method depends on whether you have access to the money. If you can withdraw the funds today (even with penalties), you calculate Zakat on the net withdrawable amount (total balance minus early withdrawal penalties and taxes). If you have no access to the funds until retirement age, scholars differ; some say you pay annually, while others say you only pay once you finally receive the money.
            </p>
        </div>

        <div style="margin-bottom: 25px;">
            <h3 style="font-size: 1.1rem; color: var(--primary-dark); margin-bottom: 8px;">9. Is Zakat due on Haram (impermissible) income?</h3>
            <p style="font-size: 0.92rem; color: var(--text-medium); line-height: 1.8;">
                No, Allah is pure and only accepts what is pure. If a person has acquired wealth through impermissible means (e.g., interest/Riba, theft, or selling forbidden goods), they cannot purify it by paying Zakat on it. The entire amount of Haram wealth must be disposed of by giving it to charity without the intention of receiving reward. Zakat is only calculated on Halal wealth.
