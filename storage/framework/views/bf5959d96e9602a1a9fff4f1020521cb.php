      <h2>Who Must Fast?</h2>
      <p>Fasting during the month of Ramadan is obligatory (Fardh) upon every Muslim who is:</p>
      <ul>
        <li><strong>Sane:</strong> Of sound mind.</li>
        <li><strong>Adult:</strong> Has reached the age of puberty.</li>
