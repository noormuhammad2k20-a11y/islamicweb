      <h2>Actions That Break the Fast (Nullifiers)</h2>
      <p>Committing any of the following actions intentionally between Fajr and Maghrib will invalidate the fast:</p>
      <ul>
        <li><strong>Eating or Drinking:</strong> Taking nourishment through the mouth intentionally.</li>
        <li><strong>Marital Relations:</strong> Sexual intercourse breaks the fast and requires severe expiation (Kaffarah).</li>
        <li><strong>Intentional Vomiting:</strong> Forcing oneself to vomit.</li>
        <li><strong>Nutritional Injections:</strong> IV drips or injections meant to provide nourishment.</li>
        <li><strong>Menstruation:</strong> The onset of menses, even moments before Maghrib, breaks the fast.</li>
      </ul>

      <h2>Actions That DO NOT Break the Fast</h2>
      <p>These actions are commonly misunderstood but they <strong>do not</strong> break the fast:</p>
      <ul>
        <li>Eating or drinking out of genuine forgetfulness.</li>
        <li>Unintentional vomiting.</li>
        <li>Swallowing one's own natural saliva.</li>
        <li>Using a Miswak (tooth stick).</li>
        <li>Bathing, swimming, or pouring water over the head (provided no water is swallowed).</li>
        <li>Using eye drops or non-nutritional medical injections (like a vaccine).</li>
        <li>Applying perfume (Ittar), lotion, or lip balm (as long as it is not ingested).</li>
      </ul>

      <h2>Makrooh (Disliked) Actions While Fasting</h2>
      <ul>
        <li>Using toothpaste (due to the risk of swallowing and strong taste).</li>
        <li>Tasting food unnecessarily (e.g., a chef may taste with the tip of the tongue and spit it out, but it is disliked).</li>
        <li>Gargling water excessively during Wudu.</li>
        <li>Engaging in arguments, backbiting, or using foul language (this severely diminishes the reward of the fast).</li>
      </ul>
