<h2>Dhu al-Qi'dah: The Sacred Month of Truce and Preparation</h2>
<p><strong>Dhu al-Qi'dah</strong> (<?php echo e($hijri_month->name_ar); ?>) is the eleventh month of the Islamic Hijri calendar and holds the prestigious status of being the first of the four sacred months (<em>Al-Ashhur Al-Hurum</em>) that occur consecutively before and during the Hajj season. The linguistic root of its name means "to sit" or "to rest," historically marking the time when pre-Islamic Arabs would cease warfare, sit in their homes, and begin peaceful preparations for the upcoming pilgrimage.</p>

<p>In the context of Islamic history, Dhu al-Qi'dah is synonymous with peace, strategic treaties, and the honoring of covenants. The most defining event of this month occurred in 6 AH, when the Prophet Muhammad (peace be upon him) and his companions set out for Umrah but were blocked by the Quraysh at Hudaybiyyah. This standoff resulted in the historic <strong>Treaty of Hudaybiyyah</strong>, a 10-year peace pact that, despite initial frustration among the companions, was declared by Allah in the Quran as a "Manifest Victory" (Fathun Mubeen). It allowed Islam to spread rapidly in an environment of unprecedented peace.</p>

<p>Furthermore, Dhu al-Qi'dah is intricately linked to the Hajj. It is the beginning of the "Months of Hajj" mentioned in the Quran, a period dedicated to spiritual orientation, physical preparation, and travel for those intending to perform the ultimate journey to the House of Allah in Makkah.</p>
